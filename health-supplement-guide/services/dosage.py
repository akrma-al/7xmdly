TIMING_LABELS = {
    "morning": "الصباح (الفطور)",
    "pre_workout": "قبل التمرين",
    "post_workout": "بعد التمرين",
    "before_sleep": "قبل النوم",
}

TIMING_ORDER = ["morning", "pre_workout", "post_workout", "before_sleep"]


def get_dosage(supplement_name):
    """Get dosage info for a supplement by name."""
    name_lower = supplement_name.lower().strip()
    if name_lower in DOSAGE_RULES:
        return DOSAGE_RULES[name_lower]
    return None


def get_schedule(user_supplements):
    """Generate a daily schedule from user's supplement list."""
    schedule = {timing: [] for timing in TIMING_ORDER}

    for us in user_supplements:
        sup = us.supplement
        if not sup:
            continue

        dosage_info = get_dosage(sup.name)
        if dosage_info:
            timing_list = dosage_info["timing"]
            dosage = us.custom_dosage or dosage_info["dosage"]
        else:
            timing_list = [sup.timing] if sup.timing else ["morning"]
            dosage = us.custom_dosage or sup.default_dosage

        if isinstance(timing_list, str):
            timing_list = [timing_list]

        for t in timing_list:
            if t in schedule:
                schedule[t].append({
                    "name": sup.name,
                    "dosage": dosage,
                    "notes": dosage_info["notes"] if dosage_info else "",
                })

    return schedule
